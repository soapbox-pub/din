#!/usr/bin/env node
// Bundle window.din's runtime (src/sdk/runtime.ts) into the app preload:
// electron/din-app-preload.cjs, with its `installDin` filled in, written out
// as electron/din-app-preload.built.cjs, which Electron loads. A sandboxed
// preload can't load a sibling file, and contextBridge.executeInMainWorld
// runs a function by its source, so the runtime has to be one function with
// nothing outside it.
//
// Likewise src/shared/caret.ts into the web pages' power mode preload:
// electron/power-mode-preload.cjs, written out as
// electron/power-mode-preload.built.cjs, and src/shared/overscroll.ts into
// every app's and page's overscroll preload: electron/overscroll-preload.cjs,
// written out as electron/overscroll-preload.built.cjs.
//
// The outputs are gitignored and rebuilt by `npm run dev`, `npm run build`,
// `npm test`, and the DinOS Nix build.

import fs from 'node:fs';
import path from 'node:path';
import { build } from 'vite';

const root = path.resolve(import.meta.dirname, '..');
const MARKER = '/* @din-runtime */ null';

const result = await build({
  configFile: false,
  logLevel: 'error',
  root,
  resolve: { alias: { '@': path.join(root, 'src') } },
  build: {
    write: false,
    copyPublicDir: false,
    minify: true,
    target: 'chrome120',
    lib: {
      entry: path.join(root, 'src/sdk/runtime.ts'),
      formats: ['iife'],
      name: 'DinRuntime',
      fileName: () => 'din-runtime.js',
    },
  },
});

const outputs = (Array.isArray(result) ? result : [result]).flatMap((r) => ('output' in r ? r.output : []));
const chunk = outputs.find((o) => o.type === 'chunk');
if (!chunk) throw new Error('build-din-runtime: no bundle');

const preload = fs.readFileSync(path.join(root, 'electron/din-app-preload.cjs'), 'utf8');
if (!preload.includes(MARKER)) throw new Error(`build-din-runtime: ${MARKER} not found in din-app-preload.cjs`);
// Returns nothing: the Din object stays in the page's world.
const func = `function installDin(transport) {\n${chunk.code}\nDinRuntime.installDin(transport);\n}`;
fs.writeFileSync(
  path.join(root, 'electron/din-app-preload.built.cjs'),
  `// Generated by scripts/build-din-runtime.mjs from din-app-preload.cjs; don't edit.\n${preload.replace(MARKER, () => func)}`,
);

/** Bundle a file of src/ as one function's body, ending with its exports as `name`. */
async function bundle(entry, name) {
  const result = await build({
    configFile: false,
    logLevel: 'error',
    root,
    resolve: { alias: { '@': path.join(root, 'src') } },
    build: {
      write: false,
      copyPublicDir: false,
      minify: true,
      target: 'chrome120',
      lib: { entry: path.join(root, entry), formats: ['iife'], name, fileName: () => `${name}.js` },
    },
  });
  const chunk = (Array.isArray(result) ? result : [result]).flatMap((r) => ('output' in r ? r.output : [])).find((o) => o.type === 'chunk');
  if (!chunk) throw new Error(`build-din-runtime: no bundle of ${entry}`);
  return chunk.code;
}

/** Write electron/<name>.built.cjs: electron/<name>.cjs with `marker` replaced by `func`. */
function writePreload(name, marker, func) {
  const source = fs.readFileSync(path.join(root, `electron/${name}.cjs`), 'utf8');
  if (!source.includes(marker)) throw new Error(`build-din-runtime: ${marker} not found in ${name}.cjs`);
  fs.writeFileSync(
    path.join(root, `electron/${name}.built.cjs`),
    `// Generated by scripts/build-din-runtime.mjs from ${name}.cjs; don't edit.\n${source.replace(marker, () => func)}`,
  );
}

writePreload(
  'overscroll-preload',
  '/* @overscroll */ null',
  `function loadOverscroll() {\n${await bundle('src/shared/overscroll.ts', 'DinOverscroll')}\nreturn DinOverscroll;\n}`,
);

const caret = await build({
  configFile: false,
  logLevel: 'error',
  root,
  resolve: { alias: { '@': path.join(root, 'src') } },
  build: {
    write: false,
    copyPublicDir: false,
    minify: true,
    target: 'chrome120',
    lib: {
      entry: path.join(root, 'src/shared/caret.ts'),
      formats: ['iife'],
      name: 'DinCaret',
      fileName: () => 'din-caret.js',
    },
  },
});
const caretChunk = (Array.isArray(caret) ? caret : [caret]).flatMap((r) => ('output' in r ? r.output : [])).find((o) => o.type === 'chunk');
if (!caretChunk) throw new Error('build-din-runtime: no caret bundle');
const CARET_MARKER = '/* @caret */ null';
const powerMode = fs.readFileSync(path.join(root, 'electron/power-mode-preload.cjs'), 'utf8');
if (!powerMode.includes(CARET_MARKER)) throw new Error(`build-din-runtime: ${CARET_MARKER} not found in power-mode-preload.cjs`);
fs.writeFileSync(
  path.join(root, 'electron/power-mode-preload.built.cjs'),
  `// Generated by scripts/build-din-runtime.mjs from power-mode-preload.cjs; don't edit.\n${powerMode.replace(
    CARET_MARKER,
    () => `function loadCaret() {\n${caretChunk.code}\nreturn DinCaret;\n}`,
  )}`,
);
