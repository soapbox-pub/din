function ContextMenuContent({
  className,
  ...props
}: React.ComponentProps<typeof ContextMenuPrimitive.Content>) {
  return (
    <ContextMenuPrimitive.Portal container={portalContainer()}>
      <ContextMenuPrimitive.Content
        data-slot="context-menu-content"
        className={cn(
          "z-50 max-h-(--radix-context-menu-content-available-height) min-w-32 origin-(--radix-context-menu-content-transform-origin) overflow-x-hidden overflow-y-auto rounded-lg glass-surface p-1.5 text-popover-foreground data-[side=bottom]:slide-in-from-top-2 data-[side=left]:slide-in-from-right-2 data-[side=right]:slide-in-from-left-2 data-[side=top]:slide-in-from-bottom-2 data-[state=closed]:animate-out data-[state=closed]:fade-out-0 data-[state=closed]:zoom-out-95 data-[state=open]:animate-in data-[state=open]:fade-in-0 data-[state=open]:zoom-in-95",
          className
        )}
        {...props}
        onPointerUpCapture={(e) => {
          // On Linux, the `contextmenu` event fires on right-button *press*,
          // so the menu is already open under the cursor when the button is
          // released. Radix MenuItem treats a pointerup without a matching
          // pointerdown as a click (to support press-drag-release), which
          // would instantly select whatever item the release lands on.
          // Swallow non-primary-button releases to prevent it; normal item
          // selection uses the native `click` event (primary button only)
          // and is unaffected.
          if (e.button !== 0) e.stopPropagation()
          props.onPointerUpCapture?.(e)
        }}
      />
    </ContextMenuPrimitive.Portal>
  )
}

