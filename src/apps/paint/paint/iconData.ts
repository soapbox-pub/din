/** The icon as SVG rects, one per horizontal run of a color. */
export function runs(name: IconName): { x: number; y: number; w: number; fill: string }[] {
  const out: { x: number; y: number; w: number; fill: string }[] = [];
  ICONS[name].forEach((row, y) => {
    let x = 0;
    while (x < 16) {
      const ch = row[x] ?? '.';
      let end = x + 1;
      while (end < 16 && (row[end] ?? '.') === ch) end++;
      const fill = INK[ch];
      if (fill) out.push({ x, y, w: end - x, fill });
      x = end;
    }
  });
  return out;
}

const cursorCache = new Map<string, string>();

/** A CSS cursor showing the icon at double size, `hot` its tip in icon pixels. */
export function iconCursor(name: IconName, hot: [number, number]): string {
  const key = `${name}:${hot.join(',')}`;
  const hit = cursorCache.get(key);
  if (hit) return hit;
  const rects = runs(name)
    .map((r) => `<rect x="${r.x}" y="${r.y}" width="${r.w}" height="1" fill="${r.fill}"/>`)
    .join('');
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="32" height="32" viewBox="0 0 16 16" shape-rendering="crispEdges">${rects}</svg>`;
  const css = `url("data:image/svg+xml,${encodeURIComponent(svg)}") ${hot[0] * 2} ${hot[1] * 2}, crosshair`;
  cursorCache.set(key, css);
  return css;
}
