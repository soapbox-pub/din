#!/usr/bin/env python3
"""Writes cmds-decl.h (how many) and cmds.h: a wrapper for every vkCmd* in vulkan_core.h that layer.c
doesn't handle itself. Each one marks its command buffer as one that can't go
to the compute queue, then passes the call on. Generating them from the
headers means a command the layer has never heard of can't slip through
unseen: whatever isn't known to be safe keeps its work where Dawn put it."""

import re
import sys

HANDLED = {
    "vkCmdBindPipeline",
    "vkCmdBindDescriptorSets",
    "vkCmdPushConstants",
    "vkCmdDispatch",
    "vkCmdDispatchIndirect",
    "vkCmdDispatchBase",
    "vkCmdDispatchBaseKHR",
    "vkCmdCopyBuffer",
    "vkCmdFillBuffer",
    "vkCmdUpdateBuffer",
    "vkCmdPipelineBarrier",
    "vkCmdBeginDebugUtilsLabelEXT",
    "vkCmdEndDebugUtilsLabelEXT",
    "vkCmdInsertDebugUtilsLabelEXT",
}

header = open(sys.argv[1]).read()
pattern = re.compile(r"typedef\s+(\w+)\s+\(VKAPI_PTR\s+\*PFN_(vkCmd\w+)\)\((.*?)\);", re.S)

commands = []
seen = set()
for ret, name, params in pattern.findall(header):
    if name in HANDLED or name in seen:
        continue
    seen.add(name)
    params = " ".join(params.split())
    parts = [p.strip() for p in params.split(",")]
    first = parts[0].split()
    if first[-1] != "commandBuffer" or first[0] != "VkCommandBuffer":
        continue
    names = []
    for p in parts:
        p = re.sub(r"\[.*?\]", "", p).strip()
        names.append(re.split(r"[\s*]+", p)[-1])
    commands.append((ret, name, params, ", ".join(names)))

with open(sys.argv[2], "w") as decl:
    decl.write("// Generated by gen-cmds.py from vulkan_core.h. Don't edit.\n")
    decl.write(f"#define GEN_CMD_COUNT {len(commands)}\n")

out = ["// Generated by gen-cmds.py from vulkan_core.h. Don't edit.", ""]
for i, (ret, name, params, args) in enumerate(commands):
    call = f"((PFN_{name})d->next_cmd[{i}])({args})"
    body = f"return {call};" if ret != "void" else f"{call};"
    out.append(f"static VKAPI_ATTR {ret} VKAPI_CALL gen_{name}({params}) {{")
    out.append(f"  struct dev *d = mark_ineligible(commandBuffer, \"{name}\");")
    out.append(f"  {body}")
    out.append("}")
out.append("")
out.append("static const char *const gen_cmd_names[GEN_CMD_COUNT] = {")
out.extend(f'  "{name}",' for _, name, _, _ in commands)
out.append("};")
out.append("static const PFN_vkVoidFunction gen_cmd_funcs[GEN_CMD_COUNT] = {")
out.extend(f"  (PFN_vkVoidFunction)gen_{name}," for _, name, _, _ in commands)
out.append("};")
open(sys.argv[3], "w").write("\n".join(out) + "\n")
